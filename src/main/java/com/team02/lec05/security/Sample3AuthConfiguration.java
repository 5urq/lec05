package com.team02.lec05.security;

import org.springframework.context.annotation.Bean;
import org.springframework.context.annotation.Configuration;
import org.springframework.security.config.annotation.web.builders.HttpSecurity;
import org.springframework.security.config.annotation.web.configuration.EnableWebSecurity;
import org.springframework.security.core.userdetails.User;
import org.springframework.security.core.userdetails.UserDetails;
import org.springframework.security.provisioning.InMemoryUserDetailsManager;
import org.springframework.security.web.SecurityFilterChain;

@Configuration
@EnableWebSecurity
public class Sample3AuthConfiguration {

  /**
   * 認可処理に関する設定
   */
  @Bean
  public SecurityFilterChain filterChain(HttpSecurity http) throws Exception {
    http.formLogin(login -> login
        .permitAll())
        .logout(logout -> logout
            .logoutUrl("/logout")
            .logoutSuccessUrl("/"))
        .authorizeHttpRequests(authz -> authz
            .anyRequest().authenticated());
    return http.build();
  }

  /**
   * 認証処理に関する設定
   * ユーザ: customer1, customer2 (CUSTOMERロール), seller (SELLERロール)
   * パスワード: p@ss ({bcrypt}$2y$10$ngxCDmuVK1TaGchiYQfJ1OAKkd64IH6skGsNw1sLabrTICOHPxC0e)
   */
  @Bean
  public InMemoryUserDetailsManager userDetailsService() {
    UserDetails customer1 = User.withUsername("customer1")
        .password("{bcrypt}$2y$10$ngxCDmuVK1TaGchiYQfJ1OAKkd64IH6skGsNw1sLabrTICOHPxC0e")
        .roles("CUSTOMER")
        .build();

    UserDetails customer2 = User.withUsername("customer2")
        .password("{bcrypt}$2y$10$ngxCDmuVK1TaGchiYQfJ1OAKkd64IH6skGsNw1sLabrTICOHPxC0e")
        .roles("CUSTOMER")
        .build();

    UserDetails seller = User.withUsername("seller")
        .password("{bcrypt}$2y$10$ngxCDmuVK1TaGchiYQfJ1OAKkd64IH6skGsNw1sLabrTICOHPxC0e")
        .roles("SELLER")
        .build();

    return new InMemoryUserDetailsManager(customer1, customer2, seller);
  }

}
